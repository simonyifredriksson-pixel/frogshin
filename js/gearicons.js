/** Stable small hash, so an item's colours never shuffle between runs. */
function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) & 0x7fffffff;
  return h;
}

const CACHE = new Map();

/**
 * Turn a picture into SVG, merging each row into horizontal runs.
 *
 * A sixteen-square icon drawn one rect per pixel is two hundred and fifty-six
 * elements and the bag holds up to thirty-six of them; run-merging takes that
 * to twenty or thirty each, which is the difference between the panel opening
 * instantly and not.
 */
function toSvg(rows, pal) {
  const out = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.' || !pal[ch]) { x++; continue; }
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      out.push(`<rect x="${x}" y="${y}" width="${w}" height="1" fill="${pal[ch]}"/>`);
      x += w;
    }
  }
  return '<svg viewBox="0 0 16 16" shape-rendering="crispEdges" '
    + `aria-hidden="true">${out.join('')}</svg>`;
}

/** The shapes that are a weapon, so a weapon is never drawn as something else. */
const WEAPON_SHAPES = new Set(['sword', 'greatsword', 'spear', 'axe', 'hammer',
  'kunai']);
/** Likewise for armour: a garment must not come out as a loaf of bread. */
const ARMOUR_SHAPES = new Set(['helm', 'crown', 'hood', 'cuirass', 'legs',
  'boots']);

/**
 * Which picture this item is drawn as.
 *
 * The glyph is the first guess and the CATEGORY is the veto. The Harrow
 * Scythe carries a 🌾, which the glyph table quite reasonably reads as bread —
 * so a weapon came out drawn as a loaf. Anything whose glyph does not name a
 * shape of the right kind falls back to its category's default.
 */
export function gearShape(item) {
  if (!item) return 'stone';
  const guess = BY_GLYPH[item.icon];
  if (guess) {
    if (item.cat === 'weapon' && !WEAPON_SHAPES.has(guess)) return 'sword';
    if (item.cat === 'armour' && !ARMOUR_SHAPES.has(guess)) {
      return item.slot === 'head' ? 'hood' : item.slot === 'legs' ? 'legs'
        : 'cuirass';
    }
    if (item.cat !== 'weapon' && WEAPON_SHAPES.has(guess) && guess !== 'kunai') {
      return BY_CAT[item.cat] || 'stone';
    }
    return guess;
  }
  return BY_CAT[item.cat] || 'stone';
}

/**
 * The icon for one item, as an SVG string.
 *
 * @param item a GEAR entry. Tier drives the metal, the id drives everything
 *             else, so the palette is a property of the item and not of when
 *             it happened to be drawn.
 */
export function gearIcon(item) {
  if (!item) return '';
  const key = item.id;
  const got = CACHE.get(key);
  if (got) return got;

  const shape = gearShape(item);
  const rows = SHAPES[shape] || SHAPES.stone;
  const h = hash(item.id);
  const tier = Math.max(0, Math.min(5, item.tier || 0));
  const [m1, m2] = METAL[tier];
  const [w1, w2] = WOOD[h % WOOD.length];
  const [c1, c2] = CLOTH[(h >> 3) % CLOTH.length];
  const acc = ACCENT[(h >> 6) % ACCENT.length];
  const pal = {
    1: m1, 2: m2, 3: w1, 4: w2, 5: acc,
    6: c1, 7: c2, 8: '#e8e2d0', 9: '#171a20',
  };
  const svg = toSvg(rows, pal);
  CACHE.set(key, svg);
  return svg;
}

/** For the inventory's category tabs, which are not items. */
const TAB_SHAPE = {
  weapon: 'sword', kunai: 'kunai', armour: 'cuirass', food: 'berry',
  material: 'stone', key: 'key',
};
export function catIcon(cat) {
  const rows = SHAPES[TAB_SHAPE[cat.id]] || SHAPES.stone;
  return toSvg(rows, {
    1: '#d6dee6', 2: '#8a95a1', 3: '#8a6a42', 4: '#54402a', 5: '#c9a227',
    6: '#d8cfae', 7: '#9a8f6a', 8: '#e8e2d0', 9: '#171a20',
  });
}

