/**
 * PIXEL-ART ICONS FOR EVERYTHING YOU CAN CARRY.
 *
 * The bag used emoji — 🗡 for every sword in the game, 🎽 for eleven different
 * garments — which meant the grid rendered in whatever house style the
 * player's operating system felt like, every weapon looked identical, and
 * none of it matched the art. This draws the items instead.
 *
 * ── how an icon is written ────────────────────────────────────────────────
 * As a picture. Each shape is a list of sixteen strings, one per row, one
 * character per pixel, and the characters are indices into a palette:
 *
 *   .  nothing        1 metal, lit    2 metal, shadow
 *   3  wood/handle    4 wood, shadow  5 the accent — gem, trim, gold
 *   6  cloth, lit     7 cloth, shadow 8 bone/white
 *   9  outline
 *
 * That is the whole format, and it is the reason there are twenty-odd icons
 * in here rather than three: writing one is drawing one.
 *
 * ── how an item gets one ─────────────────────────────────────────────────
 * `gearIcon(item)` picks the SHAPE from what the thing is — a spear is a
 * spear whatever tier it is — and the PALETTE from its tier and from a hash
 * of its own id. So the Bronze Tantō and Gravebite are recognisably the same
 * kind of object in different metal, which is what a player actually needs to
 * read off a grid of ninety-seven things.
 *
 * ── output ────────────────────────────────────────────────────────────────
 * One SVG string with `shape-rendering: crispEdges`, built by merging each
 * row into horizontal runs, so a sixteen-square icon is a couple of dozen
 * rects rather than two hundred and fifty-six. Cached by (shape, palette),
 * because the bag rebuilds its grid on every keypress.
 */

